const vm=require('node:vm');
const assert=require('node:assert/strict');
const C=require('../../src/relogio/garmin-contrato.js');
const html=fs.readFileSync(require('path').resolve(__dirname,'../../treino-app.html'),'utf8');
const days=['Seg','Ter','Qua','Qui','Sex','Sáb','Dom'];
const iso=d=>[d.getFullYear(),String(d.getMonth()+1).padStart(2,'0'),String(d.getDate()).padStart(2,'0')].join('-');
const ddmm=d=>String(d.getDate()).padStart(2,'0')+'/'+String(d.getMonth()+1).padStart(2,'0');
const run=d=>({day:d,type:'Rodagem',gpsSteps:[{name:'Rodagem',tipo:'distancia',km:5,pace:'5:00/km'}]});
